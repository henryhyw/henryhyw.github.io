// A drawing interaction changes the geometry that the next scene inherits.
export function interactivePoint(scene, stroke, point, choice) {
  if (scene === 2 && !Number.isInteger(choice)) {
    const lower = Math.floor(choice), fraction = choice - lower;
    const a = interactivePoint(scene, stroke, point, lower);
    const b = interactivePoint(scene, stroke, point, Math.ceil(choice));
    return {x:a.x+(b.x-a.x)*fraction,y:a.y+(b.y-a.y)*fraction};
  }
  let {x,y} = point;
  if (scene === 2 && stroke >= 4 && stroke <= 15) {
    const chart = stroke >= 9 && stroke <= 13;
    if (choice === 1) {
      x = chart ? 300 + (x - 387) * .83 : 300 + (x - 190) * .72;
      y = chart ? 183 + (y - 210) * .82 : 279 + (y - 210) * .35;
    } else if (choice === 2) {
      x = chart ? 365 + (x - 387) * 1.35 : 190 + (x - 190) * 1.08;
      y = chart ? 245 + (y - 210) * .68 : 151 + (y - 210) * .35;
    }
  }
  if (scene === 3 && stroke <= 3) {
    y += (1 - choice) * 14;
    y += Math.sin(x / 45 + choice * 1.7) * (choice + 1) * 2;
  }
  if (scene === 1 && stroke >= 1 && stroke <= 3) {
    x += Math.sin(point.y / 85) * (choice - 1) * 5;
  }
  return {x,y};
}
